export var TapeSymbol;
(function (TapeSymbol) {
    TapeSymbol["Blank"] = "\u25A1";
    TapeSymbol["Zero"] = "0";
    TapeSymbol["One"] = "1";
    TapeSymbol["ZeroHat"] = "0^";
    TapeSymbol["OneHat"] = "1^";
    TapeSymbol["End"] = "$";
    TapeSymbol["Separator"] = "#";
    TapeSymbol["Colon"] = ":";
    TapeSymbol["Wildcard"] = "*";
})(TapeSymbol || (TapeSymbol = {}));
